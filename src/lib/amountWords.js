/** 0 … 99,99,99,99,999 in Hindi words (Indian grouping: करोड़, लाख, हज़ार, सौ). */
export function hindiNumber(n) {
  n = Math.floor(Math.abs(Number(n) || 0));
  if (n < 100) return ONES[n];
  const parts = [];
  const take = (div, word) => {
    const q = Math.floor(n / div);
    if (q) { parts.push(`${q >= 100 ? hindiNumber(q) : ONES[q]} ${word}`); n %= div; }
  };
  take(10000000, "करोड़");
  take(100000, "लाख");
  take(1000, "हज़ार");
  take(100, "सौ");
  if (n) parts.push(ONES[n]);
  return parts.join(" ");
}

/** "एक हज़ार पाँच सौ रुपये मात्र" */
export function rupeesInWords(amount) {
  const n = Math.round(Number(amount) || 0);
  return `${hindiNumber(n)} रुपये मात्र`;
}
